import { test, expect } from "bun:test";
import { findProfanity, isClean } from "../../v2/profanity.mjs";

const BAD = ["Ну и хрень, иди нахер", "это пиздец", "п*здец какой-то", "бл*ть", "бля, ну", "ёпт", "ЁПЫРЭСЭТЕ", "охуеть", "заебись", "х у й", "х.у.й", "xуй", "пиzдец", "сука", "мудак", "херня", "похер", "п...ц", "б**", "f*ck", "shit", "долбоеб", "выебон", "жопа", "говно", "пипец", "ахуеваю", "Не обязательно отправлять человека нахер"];
const GOOD = ["Сегодня небо ясное и хлеб свежий", "дай себе паузу, себя береги, себестоимость", "похудеть, ухудшить, набережная, преобразование, побег, победа, обед", "Оскорблять никого не нужно", "Застрахуйте машину", "мандарин и мандат", "херувим", "команда и корабля", "Т.е. всё хорошо, и т.д.", "Ну... посмотрим", "Пиши @liz_ty666", "Мои красивые, кошки, дефки — СЕГОДНЯ БЕЗ СПЕШКИ 🖤", "ребёнок, учеба, требовать, употреблять", "Луна в Скорпионе", "хрен с ним", "офигеть", "мудрость и мудрый совет", "сукно"];

test("мат и замаскированный мат находятся", () => {
  for (const s of BAD) expect(findProfanity(s).length, s).toBeGreaterThan(0);
});
test("обычные слова не считаются матом", () => {
  for (const s of GOOD) expect(findProfanity(s), s).toEqual([]);
});
test("isClean", () => { expect(isClean("Всё спокойно 🖤")).toBe(true); expect(isClean("бл@дь")).toBe(false); });
