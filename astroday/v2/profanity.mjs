// ASTRODAY 2.0 — проверка на нецензурную и замаскированную лексику.
// Политика: в любых текстах ASTRODAY мата нет вообще — ни прямого, ни замаскированного
// (звёздочки, латиница вместо кириллицы, точки/пробелы внутри слова, эвфемизмы-заменители).
// Детектор намеренно строгий: ложное срабатывание = перегенерация, пропуск = недопустим.

const LOOKALIKE = { a: "а", b: "в", c: "с", e: "е", h: "н", k: "к", m: "м", o: "о", p: "р", t: "т", x: "х", y: "у", u: "и", z: "з", r: "р", n: "п", "0": "о", "3": "з", "6": "б", "@": "а", "$": "с", "ё": "е" };
const MASK = /[*#%@$_]|\.{2,}|…/;

// Корни, запрещённые в начале слова (после допустимой приставки).
const PREFIX = "(?:|за|на|по|от|до|об|о|вы|при|пере|раз|рас|недо|у|с|съ|из|под|въ|в|не|ни|долбо|отъ|объ)";
const PREFIX_EB = "(?:|за|на|по|от|до|вы|при|пере|раз|недо|у|из|под|долбо|отъ|объ|съ|въ|подъ|изъ|разъ|не|ни|про)";
const ROOTS = [
  new RegExp("^" + PREFIX + "ху[йяеёию]"),
  /пизд/,
  new RegExp("^" + PREFIX_EB + "еб(?!ед|ер|ен(?!ь))"),
  new RegExp("^" + PREFIX_EB + "ёб"),
  /^бл[яе][дтх]/,
  /^бля$/,
  /^бляд/,
  /^муд(ак|ач|ил|оз|оха)/,
  /^пид[оа]р/,
  /^пидр/,
  /^сук(а|и|у|ой|ам|ами|ах|ин|ина|ины|ин[ао]м)?$/,
  new RegExp("^" + PREFIX + "хер(?!увим|сон|ес|ц)"),
  /^залуп/,
  /^манд(а|ы|е|у|ой|ец|ёж|еж)$/,
  /^шлюх/,
  /^говн/,
  /^жоп/,
  /^[её]п(т|ры|ы|рс|эр|ер|с|ан|ен)/,
  /^пипец/,
  /^(ах|ох|ух)у[ейиё]/,
  /^уеб/,
  /^(f+u+c+k|sh[i1]t|b[i1]tch|wtf)/,
];

// Исключения: легитимные слова, ловящиеся корнями выше.
const ALLOW = new Set(["небо", "небе", "небу", "небом", "хлеб", "рубля", "корабля", "оскорблять", "употреблять", "страхуй", "застрахуй", "застрахуйте", "мандарин", "мандат", "сукно", "херувим", "херес", "учеба", "учеб", "ребенок", "ребёнок"]);

function normalizeWord(w) {
  let s = w.toLowerCase().replace(/ё/g, "е");
  // латиница-двойники только если в слове есть кириллица (иначе это английское слово)
  if (/[а-я]/.test(s)) s = [...s].map((c) => LOOKALIKE[c] ?? c).join("");
  return s;
}

// Слова, разбитые разделителями: «х у й», «х.у.й», «п-и-з-д»
function collapseSpaced(text) {
  return text.replace(/(?:^|(?<=\s))((?:[а-яёa-z](?:[\s.\-_·•]+)){2,}[а-яёa-z])(?=\s|$|[,!?;:])/giu, (m) => m.replace(/[\s.\-_·•]+/g, ""));
}

export function findProfanity(text) {
  const hits = [];
  const src = collapseSpaced(String(text ?? "").normalize("NFC"));
  const tokens = src.split(/[^\p{L}\p{N}*#%@$_.…]+/u).filter(Boolean);
  for (const raw of tokens) {
    const tok = raw.replace(/^[.…]+|[.…]+$/g, "");
    if (!tok) continue;
    if (/^@[a-z0-9_]{3,}$/i.test(tok)) continue; // @username
    const letters = tok.replace(/[^\p{L}]/gu, "");
    // замаскированное слово: буквы + маскирующие символы внутри слова
    if (MASK.test(tok) && /\p{L}/u.test(tok) && letters.length >= 1 && /\p{L}[*#%@$_.…]+\p{L}?|^[*#%@$_]+\p{L}|\p{L}[*#%@$_]+$/u.test(tok) && !/^\p{L}+\.\p{L}+$/u.test(tok)) {
      hits.push({ word: raw, reason: "masked" });
      continue;
    }
    const w = normalizeWord(letters);
    if (!w || ALLOW.has(w)) continue;
    if (ROOTS.some((re) => re.test(w))) hits.push({ word: raw, reason: "obscene" });
  }
  return hits;
}

export function isClean(text) {
  return findProfanity(text).length === 0;
}
