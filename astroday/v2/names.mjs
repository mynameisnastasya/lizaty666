const cap = (s) => (s ? s[0].toLocaleUpperCase("ru-RU") + s.slice(1) : s);

export function cleanName(raw) {
  return String(raw ?? "").normalize("NFC").replace(/[<>&"'`\\\u0000-\u001f​-‏⁠]/g, "").replace(/\s+/g, " ").trim().slice(0, 32);
}

// Имя (первое слово) из анкеты/Telegram: «Дарья Белоусова» → «Дарья»
export function firstName(raw) {
  const s = cleanName(raw).split(" ")[0] || "";
  return /^[\p{L}][\p{L}\-]{0,30}$/u.test(s) ? cap(s.toLocaleLowerCase("ru-RU")) : "";
}

export function nameOptions(raw) {
  const first = firstName(raw);
  if (!first) return [];
  const forms = FORMS[first.toLocaleLowerCase("ru-RU")];
  const opts = [{ mode: "original", value: first }];
  if (forms) for (const f of forms) if (f !== first && !opts.some((o) => o.value === f)) opts.push({ mode: "affectionate", value: f });
  return opts;
}

// Итоговое обращение по настройкам: mode = original | affectionate | custom | none
export function addressName({ profileName, mode = "original", custom = null, affectionate = null }) {
  if (mode === "none") return "";
  if (mode === "custom") {
    const c = cleanName(custom);
    return /^[\p{L}][\p{L}\- ]{0,30}$/u.test(c) ? c : firstName(profileName);
  }
  if (mode === "affectionate" && affectionate) {
    const ok = nameOptions(profileName).some((o) => o.value === affectionate);
    if (ok) return affectionate;
  }
  return firstName(profileName);
}

// Грамматический род — только по полному имени из анкеты (не по username). Неизвестно → null (нейтральные формулировки).
const MALE = new Set(["александр", "алексей", "дмитрий", "сергей", "андрей", "михаил", "иван", "никита", "евгений", "максим", "владимир", "николай"]);
export function grammaticalGender(raw) {
  const f = firstName(raw).toLocaleLowerCase("ru-RU");
  if (!f) return null;
  if (MALE.has(f)) return "m";
  if (FORMS[f]) return "f";
  return null;
}
